// 取穴法：實際要怎麼把針下在對的地方
//
// data/acupoints.js 的 loc 是 WHO 標準定位的「敘述」，回答的是「這個穴在哪裡」；
// 這裡的 find 回答的是「我現在要怎麼找到它」——擺什麼姿勢、先摸哪一個骨性標誌、
// 從哪裡往哪裡量幾寸、下針前用什麼確認沒找錯。
//
// cun  { seg, n, from? }  骨度分寸錨點，只有落在長骨骨度尺上的四肢穴位才有。
//      seg  對應 data/cun.js 的 BONE_CUN
//      n    從尺的遠端標誌往近端量幾寸（腕橫紋上 7 寸 → { seg:'forearm', n:7 }）；
//           負數代表往遠端量（照海在內踝尖「下」1 寸 → n:-1）
//      from 改用別的標誌當起算點，但仍沿用該段骨度的 1 寸長度
//           （伏兔是「髕底上 6 寸」，髕底比膕橫紋高 1.5 寸左右，不換起算點會整排偏低）
//
// 有 cun 的穴位，沿骨長軸的位置由寸數直接算出來，不再依賴 pos 的 y 值；
// pos 只用來決定橫向偏在骨頭的哪一側。npm run validate 會反算兩者是否一致。
//
// 「一夫法」＝四指併攏為 3 寸、「二橫指」≈1.5 寸、「拇指同身寸」＝拇指指間關節寬為 1 寸，
// 都是受檢者本人的手指，不是施術者的。詳見 data/cun.js 的 FINGER_CUN。

